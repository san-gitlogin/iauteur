ROOT = Path(__file__).resolve().parents[2]

# ---------------------------------------------------------------------------
# .env loading (stdlib — no python-dotenv dependency). Never overwrites an env
# var that is already set in the process, so real env wins over the file.
# ---------------------------------------------------------------------------

def load_env(path: Path | None = None) -> None:
    envfile = path or (ROOT / ".env")
    try:
        text = envfile.read_text(encoding="utf-8")
    except OSError:
        return
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        key = key.strip()
        val = val.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = val


