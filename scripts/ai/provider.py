#!/usr/bin/env python3
"""iAuteur AI provider adapter — ONE `.complete(prompt)` across any AI API.

This is the single non-deterministic step in the automated pipeline: it takes a
prompt string (generated by the existing deterministic scripts) and returns the
model's text. Everything else (lint, normalize, assemble, fix-loop) stays the
judge, exactly as in the manual copy-paste flow.

Engines (selected by config; ZERO required third-party deps for the core path —
the OpenAI-compatible chat-completions call is a plain HTTPS POST via stdlib):

  azure           classic Azure OpenAI chat completions
                  {endpoint}/openai/deployments/{deployment}/chat/completions?api-version=...
                  auth header: api-key
  azure_v1        Azure OpenAI v1 surface: {endpoint}/openai/v1/chat/completions
                  auth header: Authorization: Bearer  (model = deployment name)
  openai          OpenAI OR any OpenAI-compatible base_url — covers Hugging Face
                  router (https://router.huggingface.co/v1), Groq, Together,
                  OpenRouter, Ollama, local vLLM / LM Studio, etc.
  litellm         OPTIONAL — only used if the `litellm` package is installed;
                  unlocks the non-OpenAI-shaped tail (Bedrock, Vertex, Anthropic
                  native, Cohere, …). Import-guarded; never required.

SECURITY: API keys are read ONLY from the process env or a gitignored `.env`.
They are NEVER logged, echoed, printed, or written to any tracked file. The
`--dry-run` and status paths mask the key.

Verified against live docs (2026-07-22): OpenAI-compatible /v1/chat/completions
is the universal standard; HF Inference Providers is a drop-in OpenAI-compatible
router; Azure OpenAI is reachable with api-key on the classic deployments URL.
"""
from __future__ import annotations

